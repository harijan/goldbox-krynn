static const int32_t volumes[16] = {8191, 6506, 5168, 4105, 3261, 2590, 2057, 1634,
                                    1298, 1031, 819,  651,  517,  411,  326,  0};

int32_t cok_sound_volume(unsigned attenuation)
{
    return volumes[attenuation & 15];
}

/* The NCR 8496 as MAME has it: a 16-bit shift register fed back at bit 15,
 * tapped at bits 1 and 5, the taps XNOR'd for white noise; reset only when
 * the white/periodic bit changes. */
enum { FEEDBACK = 0x8000, TAP1 = 0x02, TAP2 = 0x20 };

void cok_sound_chip_init(cok_sound_chip *chip)
{
    memset(chip, 0, sizeof *chip);
    for (int i = 0; i < 8; i += 2) chip->reg[i + 1] = 0x0f;
    for (int i = 0; i < 3; ++i) chip->period[i] = 0x400;
    chip->rng = FEEDBACK;
    chip->output[3] = (uint8_t)(chip->rng & 1);
}

static void noise_period(cok_sound_chip *chip)
{
    uint16_t n = chip->reg[6];
    chip->period[3] = (n & 3) == 3 ? chip->period[2] << 1 : 1 << (5 + (n & 3));
}

void cok_sound_chip_write(cok_sound_chip *chip, uint8_t value)
{
    unsigned r;
    if (value & 0x80) {
        r = (unsigned)(value & 0x70) >> 4;
        chip->latched = (uint8_t)r;
        if (r == 6 && (value & 0x04) != (chip->reg[6] & 0x04)) chip->rng = FEEDBACK;
        chip->reg[r] = (uint16_t)((chip->reg[r] & 0x3f0) | (value & 0x0f));
    } else {
        r = chip->latched;
    }
    unsigned c = r >> 1;
    switch (r) {
    case 0: case 2: case 4:
        if ((value & 0x80) == 0)
            chip->reg[r] = (uint16_t)((chip->reg[r] & 0x0f) | (value & 0x3f) << 4);
        chip->period[c] = chip->reg[r] != 0 ? chip->reg[r] : 0x400;
        if (r == 4 && (chip->reg[6] & 3) == 3) chip->period[3] = chip->period[2] << 1;
        break;
    case 1: case 3: case 5: case 7:
        if ((value & 0x80) == 0) chip->reg[r] = (uint16_t)((chip->reg[r] & 0x3f0) | (value & 0x0f));
        break;
    case 6:
        if ((value & 0x80) == 0) chip->reg[r] = (uint16_t)((chip->reg[r] & 0x3f0) | (value & 0x0f));
        noise_period(chip);
        break;
    }
}

void cok_sound_chip_step(cok_sound_chip *chip)
{
    for (int i = 0; i < 3; ++i) {
        if (--chip->count[i] <= 0) {
            chip->output[i] ^= 1;
            chip->count[i] = chip->period[i];
        }
    }
    if (--chip->count[3] <= 0) {
        bool tap1 = (chip->rng & TAP1) != 0, tap2 = (chip->rng & TAP2) != 0;
        bool white = (chip->reg[6] & 4) != 0;
        /* Periodic noise takes the first tap alone; white noise XNORs both. */
        bool feedback = white ? tap1 != !tap2 : tap1;
        chip->rng = (uint16_t)(chip->rng >> 1 | (feedback ? FEEDBACK : 0));
        chip->output[3] = (uint8_t)(chip->rng & 1);
        chip->count[3] = chip->period[3];
    }
}

int32_t cok_sound_chip_level(const cok_sound_chip *chip)
{
    int32_t level = 0;
    for (int i = 0; i < 4; ++i)
        if (chip->output[i]) level += volumes[chip->reg[2 * i + 1] & 15];
    return level;
}

/* The ports. */

static uint32_t pit2_half(const cok_sound *s, bool high)
{
    uint32_t n = s->pit2 != 0 ? s->pit2 : 65536;
    uint32_t half = high ? (n + 1) / 2 : n / 2;
    return half > 0 ? half : 1;
}

void cok_sound_out(cok_sound *s, uint16_t port, uint8_t value)
{
    if (s->trace != NULL) s->trace(s->trace_context, port, value);
    switch (port) {
    case 0x40:
        if (!s->pit0_hi) {
            s->pit0_lo = value;
            s->pit0_hi = true;
        } else {
            s->pit0 = (uint16_t)(value << 8 | s->pit0_lo);
            s->pit0_hi = false;
            if (s->pit0_restart) {
                /* After a control word the count starts at once; else it
                 * takes over when the current one runs out. */
                s->pit0_restart = false;
                s->next_tick = s->now + (uint64_t)(s->pit0 != 0 ? s->pit0 : 65536) * PIT_CLOCKS;
            }
        }
        break;
    case 0x42:
        if (!s->pit2_hi) {
            s->pit2_lo = value;
            s->pit2_hi = true;
        } else {
            s->pit2 = (uint16_t)(value << 8 | s->pit2_lo);
            s->pit2_hi = false;
            if (s->pit2_waiting) {
                s->pit2_waiting = false;
                s->pit2_out = true;
                s->pit2_left = pit2_half(s, true);
            }
        }
        break;
    case 0x43:
        if ((value >> 6) == 0) {
            s->pit0_hi = false;
            s->pit0_restart = true;
        } else if ((value >> 6) == 2) {
            s->pit2_hi = false;
            s->pit2_waiting = true;
            s->pit2_out = true;
        }
        break;
    case 0x61: {
        uint8_t old = s->port61;
        s->port61 = value;
        if ((old & 1) != (value & 1)) {
            /* Gate low holds the output high; rising, it restarts the count. */
            s->pit2_out = true;
            if (value & 1) s->pit2_left = pit2_half(s, true);
        }
        break;
    }
    case 0xc0:
        if (s->hardware == COK_SOUND_TANDY) cok_sound_chip_write(&s->chip, value);
        break;
    case 0x388:
        if (s->hardware == COK_SOUND_ADLIB) cok_opl2_write_address(&s->opl, value);
        break;
    case 0x389:
        if (s->hardware == COK_SOUND_ADLIB) cok_opl2_write_data(&s->opl, value);
        break;
    default:
        break;
    }
}

static void out(cok_sound *s, uint16_t port, uint8_t value)
{
    cok_sound_out(s, port, value);
}

static void silence_tandy(cok_sound *s)
{
    out(s, 0xc0, 0x9f);
    out(s, 0xc0, 0xbf);
    out(s, 0xc0, 0xdf);
    out(s, 0xc0, 0xff);
}

/* The effects driver, 17e8. Its data segment is s->fx; offsets as there. */

#define FX (s->fx)

/* 0x1597's fields: everything of a channel but its count and script. */
static void fx_clear(cok_sound *s, uint16_t si)
{
    static const uint8_t fields[] = {4, 6, 8, 0xa, 0xc, 0x10, 0x12, 0x16, 0x18,
                                     0x1a, 0x1c, 0x1e, 0x20, 0x22, 0x24};
    for (size_t i = 0; i < sizeof fields; ++i) ww(FX, (uint16_t)(si + fields[i]), 0);
}

/* 15d8: the end of a script's run for this tick: the channel keeps the
 * script's place, or with its count 0 stops (script pointer 0). */
static void fx_end(cok_sound *s, uint16_t di)
{
    uint16_t si = rw(FX, 0x14a);
    if (rw(FX, si) == 0) {
        FX[0x152 + (uint8_t)(4 - FX[0x122])] = 0;
        di = 0;
    }
    ww(FX, (uint16_t)(si + 2), di);
}

/* 160d: note events, three bytes each: channel (bits 5-7, only 0 sets a
 * note), note (bit 7 the group's last, 0x7f a rest), duration (times
 * +0xe when that is above 1). The duration goes to the channel running the
 * script; the note to channel 0 of the set, octaves from the note table
 * at 014e shifted right. */
static void fx_notes(cok_sound *s, uint16_t si, uint16_t di, uint8_t bl)
{
    for (int steps = 0; steps < STEPS_MAX; ++steps) {
        uint16_t b = di;
        uint8_t cl = (uint8_t)(bl >> 5);
        uint16_t target = (uint16_t)(cl * FX[0x123] + rw(FX, 0x14c));
        uint16_t ax = rw(FX, (uint16_t)(si + 0xe));
        if ((uint8_t)ax <= 1)
            ax = FX[(uint16_t)(b + 1)];
        else
            ax = (uint16_t)((uint8_t)ax * FX[(uint16_t)(b + 1)]);
        ww(FX, si, ax);
        ax = FX[b] & 0x7f;
        if (ax != 0x7f && cl == 0) {
            uint16_t cx = rw(FX, si);
            ww(FX, target, cx);
            ww(FX, (uint16_t)(target + 0x14), cx);
            ax = (uint16_t)(ax + rw(FX, (uint16_t)(target + 0x12)));
            ww(FX, (uint16_t)(target + 0x18), 0);
            ww(FX, (uint16_t)(target + 0x1a), 1);
            uint8_t octave = (uint8_t)(ax / 12);
            uint16_t at = (uint16_t)((ax % 12) * 2 + rw(FX, 0x14e));
            uint16_t pitch = (uint16_t)(octave >= 16 ? 0 : rw(FX, at) >> octave);
            ww(FX, (uint16_t)(target + 4), pitch);
            ww(FX, (uint16_t)(target + 8), pitch);
        }
        uint8_t al = FX[b];
        di = (uint16_t)(b + 2);
        if (al & 0x80) {
            fx_end(s, di);
            return;
        }
        bl = FX[di];
        di = (uint16_t)(di + 1);
    }
}

/* 1554: run the channel's script until a group of notes or an end. */
static void fx_script(cok_sound *s, uint16_t si)
{
    uint16_t di = rw(FX, (uint16_t)(si + 2));
    if (di == 0) return;
    ww(FX, 0x14a, si);
    for (int steps = 0; steps < STEPS_MAX; ++steps) {
        uint8_t bl = FX[di];
        di = (uint16_t)(di + 1);
        if (bl < 0xfa) {
            fx_notes(s, si, di, bl);
            return;
        }
        uint16_t handler = rw(FX, (uint16_t)(0x16a + (uint8_t)((bl - 0xfa) * 2)));
        switch (handler) {
        case 0x1597: /* 0xfa: clear this channel */
            fx_clear(s, si);
            break;
        case 0x15f5: /* 0xfb: return */
            di = rw(FX, 0x150);
            break;
        case 0x15fc: { /* 0xfc: call */
            uint16_t to = rw(FX, di);
            di = (uint16_t)(di + 2);
            ww(FX, 0x150, di);
            di = to;
            break;
        }
        case 0x158e: /* 0xfd: go on with another channel, cleared */
            si = (uint16_t)(rw(FX, di) + rw(FX, 0x14c));
            di = (uint16_t)(di + 2);
            fx_clear(s, si);
            break;
        case 0x1577: { /* 0xfe: loop while the counter at a field runs down */
            uint16_t field = (uint16_t)(si + FX[di]);
            uint16_t to = rw(FX, (uint16_t)(di + 1));
            di = (uint16_t)(di + 3);
            uint16_t count = rw(FX, field);
            if (count != 0) {
                ww(FX, field, count - 1u);
                if (count == 1) break;
            }
            di = to;
            break;
        }
        case 0x15c8: { /* 0xff: set a field; field 0 (the count) ends */
            uint8_t field = FX[di];
            uint16_t value = rw(FX, (uint16_t)(di + 1));
            di = (uint16_t)(di + 3);
            ww(FX, (uint16_t)(si + field), value);
            if (field != 0) break;
            fx_end(s, di);
            return;
        }
        default:
            return; /* The table names these six only. */
        }
    }
}

/* 14c3: a channel's tick: volume and pitch slides, vibrato, the note-off
 * countdown, the script when the count runs out, the envelope. */
static void fx_channel(cok_sound *s, uint16_t si)
{
    ww(FX, (uint16_t)(si + 0xa), rw(FX, (uint16_t)(si + 0xa)) + rw(FX, (uint16_t)(si + 0xc)));
    ww(FX, (uint16_t)(si + 4), rw(FX, (uint16_t)(si + 4)) + rw(FX, (uint16_t)(si + 6)));
    uint16_t dx = 0;
    uint16_t ax = (uint16_t)(rw(FX, (uint16_t)(si + 0x1e)) + rw(FX, (uint16_t)(si + 0x20)));
    if (ax != 0) {
        uint16_t length = rw(FX, (uint16_t)(si + 0x24));
        if (ax >= length) ax = (uint16_t)(ax - length);
        ww(FX, (uint16_t)(si + 0x1e), ax);
        uint16_t at = (uint16_t)(sar(ax, 4) + rw(FX, (uint16_t)(si + 0x1c)));
        int32_t sample = s16((uint16_t)(FX[at] << 8));
        int32_t product = sample * s16(rw(FX, (uint16_t)(si + 0x22)));
        dx = (uint16_t)((uint32_t)product >> 16);
    }
    dx = (uint16_t)(dx + rw(FX, (uint16_t)(si + 4)));
    ww(FX, (uint16_t)(si + 8), dx);
    uint16_t off = rw(FX, (uint16_t)(si + 0x14));
    if (off != 0) {
        ww(FX, (uint16_t)(si + 0x14), off - 1u);
        if (off == 1) {
            ww(FX, (uint16_t)(si + 0x18), 0x10);
            ww(FX, (uint16_t)(si + 0x1a), 1);
        }
    }
    uint16_t count = (uint16_t)(rw(FX, si) - 1);
    ww(FX, si, count);
    if (count == 0) fx_script(s, si);
    uint16_t step = rw(FX, (uint16_t)(si + 0x1a));
    if (step == 0) return;
    ww(FX, (uint16_t)(si + 0x1a), step - 1u);
    if (step != 1) return;
    /* In the original's order of reads and writes: a table pointing into
     * the channel itself sees its own writes. */
    for (int steps = 0; steps < STEPS_MAX; ++steps) {
        uint16_t bx = (uint16_t)(rw(FX, (uint16_t)(si + 0x16)) + rw(FX, (uint16_t)(si + 0x18)));
        if (rw(FX, (uint16_t)(bx + 2)) == 0xffff) {
            /* A level: the volume set, its slide stopped at 0. */
            uint16_t level = rw(FX, bx);
            ww(FX, (uint16_t)(si + 0xa), level);
            if (level == 0) ww(FX, (uint16_t)(si + 0xc), 0);
            ww(FX, (uint16_t)(si + 0x18), rw(FX, (uint16_t)(si + 0x18)) + 4u);
            continue;
        }
        ww(FX, (uint16_t)(si + 0xc), rw(FX, bx));
        ww(FX, (uint16_t)(si + 0x1a), rw(FX, (uint16_t)(bx + 2)));
        ww(FX, (uint16_t)(si + 0x18), rw(FX, (uint16_t)(si + 0x18)) + 4u);
        return;
    }
}

/* 13c0: the speaker's channels; the first sounding one drives PIT
 * channel 2 and port 0x61 bits 0-1 (its volume & 3). */
static void fx_speaker(cok_sound *s)
{
    uint8_t bits = 0;
    if (rw(FX, 0x148) != 0) {
        ww(FX, 0x30e, 0);
        FX[0x122] = 4;
        ww(FX, 0x14e, 0x2f6);
        uint16_t si = 0x176;
        ww(FX, 0x14c, si);
        do {
            if (rw(FX, si) != 0) {
                fx_channel(s, si);
                if (rw(FX, 0x30e) == 0 && rw(FX, (uint16_t)(si + 0xa)) != 0 && rw(FX, si) != 0)
                    ww(FX, 0x30e, si);
            }
            si = (uint16_t)(si + 0x30);
        } while (--FX[0x122] != 0);
        uint16_t chosen = rw(FX, 0x30e);
        if (FX[0x156] != 0 && chosen != 0) {
            uint16_t pitch = rw(FX, (uint16_t)(chosen + 8));
            out(s, 0x42, (uint8_t)pitch);
            out(s, 0x42, (uint8_t)(pitch >> 8));
            bits = (uint8_t)(rw(FX, (uint16_t)(chosen + 0xa)) & 3);
        }
    }
    out(s, 0x61, (uint8_t)((s->port61 & 0xfc) | bits));
}

/* 1435: the Tandy's channels, then every voice's pitch and volume
 * written (the noise voice only its first byte, its control). */
static void fx_tandy(cok_sound *s)
{
    if (rw(FX, 0x148) == 0) {
        silence_tandy(s);
        return;
    }
    FX[0x122] = 4;
    ww(FX, 0x14e, 0x490);
    uint16_t si = 0x310;
    ww(FX, 0x14c, si);
    do {
        if (rw(FX, si) != 0) fx_channel(s, si);
        si = (uint16_t)(si + 0x30);
    } while (--FX[0x122] != 0);
    if (FX[0x156] == 0) {
        silence_tandy(s);
        return;
    }
    FX[0x122] = 4;
    si = 0x310;
    uint8_t dl = 0x80;
    do {
        uint16_t ax = (uint16_t)(rw(FX, (uint16_t)(si + 8)) >> 2);
        out(s, 0xc0, (uint8_t)(((ax & 0xff) >> 4) ^ dl));
        if (dl != 0xe0) out(s, 0xc0, (uint8_t)(ax >> 8));
        ax = (uint16_t)(0xffff - rw(FX, (uint16_t)(si + 0xa)));
        out(s, 0xc0, (uint8_t)((((ax >> 8) >> 4) ^ dl) + 0x10));
        dl = (uint8_t)(dl + 0x20);
        si = (uint16_t)(si + 0x30);
    } while (--FX[0x122] != 0);
}

/* 168b (speaker, tables at 04a8) and 16f7 (Tandy, 0550): start sound n on
 * each channel its entry names. */
static void fx_start(cok_sound *s, uint16_t n, uint16_t table, uint16_t base)
{
    ww(FX, 0x148, n);
    uint16_t si = (uint16_t)(n * 8);
    FX[0x121] = 1;
    FX[0x122] = 4;
    uint16_t di = base;
    do {
        uint16_t script = rw(FX, (uint16_t)(si + table));
        if (script != 0) {
            for (int bx = 0x2e; bx >= 0; bx -= 2) ww(FX, (uint16_t)(di + bx), 0);
            ww(FX, (uint16_t)(di + 2), script);
            FX[0x152 + (uint8_t)(4 - FX[0x122])] = (uint8_t)rw(FX, 0x148);
            ww(FX, di, 1);
        }
        di = (uint16_t)(di + 0x30);
        si = (uint16_t)(si + 2);
    } while (--FX[0x122] != 0);
    FX[0x121] = 0;
}

static void fx_speaker_start(cok_sound *s, uint16_t n)
{
    fx_start(s, n, 0x4a8, 0x176);
}

static void fx_tandy_start(cok_sound *s, uint16_t n)
{
    fx_start(s, n, 0x550, 0x310);
}

/* 12c5: hook INT 8, PIT channel 0 to 0x13b1 (after channel 2's control
 * word: channel 0 takes the count in its own mode). */
static void fx_hook(cok_sound *s)
{
    s->fx_saved = s->isr;
    s->isr = COK_SOUND_FX;
    out(s, 0x43, 0xb6);
    out(s, 0x40, 0xb1);
    out(s, 0x40, 0x13);
}

/* 12fa: unhook, PIT channel 0 back to 0xffff, the speaker and the voices
 * silenced. */
static void fx_unhook(cok_sound *s)
{
    s->isr = s->fx_saved;
    out(s, 0x40, 0xff);
    out(s, 0x40, 0xff);
    out(s, 0x61, (uint8_t)(s->port61 & 0xfc));
    silence_tandy(s);
}

static void chain(cok_sound *s, cok_sound_isr to);

/* 1333. */
static void fx_interrupt(cok_sound *s)
{
    uint16_t bomb = rw(FX, 0x124);
    if (bomb != 0) {
        ww(FX, 0x124, bomb - 1u);
        if (bomb == 1) {
            /* "Run-time  Error 209 at 0BAD:0038" and back to DOS. */
            s->bomb = true;
            return;
        }
    }
    if (FX[0x121] == 0) {
        FX[0x121] = 1;
        fx_speaker(s);
        fx_tandy(s);
        FX[0x121] = 0;
    }
    if (--FX[0x120] == 0) {
        FX[0x120] = 0x0d; /* Every 13th tick, on to the handler it replaced. */
        chain(s, s->fx_saved);
    }
}

void cok_sound_command(cok_sound *s, unsigned n)
{
    if (s->music) return;
    uint8_t low = (uint8_t)n;
    if ((FX[low >> 3] & (1u << (low & 7))) == 0) return; /* the set at 17e8:0000 */
    bool on = s->device != COK_SOUND_NONE;
    if (n == 0) {
        if (on) {
            fx_tandy_start(s, 0);
            fx_speaker_start(s, 0);
        }
    } else if (n == 1) {
        if (on) FX[0x156] = 1; /* 1763 */
    } else if (n == 0xff) {
        if (on) {
            fx_tandy_start(s, 0);
            fx_speaker_start(s, 0);
            fx_unhook(s);
            s->installed = false;
        }
    } else if (n >= 2 && n <= 12) {
        if (on) {
            if (s->device == COK_SOUND_TANDY)
                fx_tandy_start(s, (uint16_t)(n - 1));
            else
                fx_speaker_start(s, (uint16_t)(n - 1));
        }
    } else if (n == 15) {
        ww(FX, 0x124, 5000); /* through DS:4b22, set by 17e8:0105 */
    }
}

/* 00da. */
static void fx_install(cok_sound *s)
{
    s->saved = s->device;
    s->installed = true;
    if (s->device == COK_SOUND_NONE) return;
    fx_hook(s);
    fx_speaker_start(s, 0);
    fx_tandy_start(s, 0);
}

/* The music drivers: MIDI.DAX record 3 (AdLib), 4 (Tandy) and 5 (speaker), each
 * called with AH = 0 (a tick), 1 (play the score) or 2 (stop) through the
 * table its entry reads; their data in their own segment (s->music_seg),
 * the score in s->score_seg. */

#define MD (s->music_seg)
#define SC (s->score_seg)

typedef struct {
    uint16_t table;    /* where the entry (0203 / 0120) finds AH's routine */
    uint16_t tick, play, stop;
} music_entry;

static const music_entry adlib_entry = {0x355, 0x3ee, 0x376, 0x3e3};
static const music_entry tandy_entry = {0x1fd, 0x2aa, 0x21e, 0x292};
static const music_entry speaker_entry = {0x11a, 0x1b0, 0x13b, 0x19d};

static const music_entry *music_driver(const cok_sound *s)
{
    return s->hardware == COK_SOUND_TANDY  ? &tandy_entry
           : s->hardware == COK_SOUND_ADLIB ? &adlib_entry
                                            : &speaker_entry;
}

/* MIDI.DAX record 3, the AdLib's: as many voices as the chip has channels
 * (nine, melodic: it never sets rhythm mode), each at a MIDI channel of
 * the score's bytes 0x22-0x2a. Per voice at 02d4 channel, 02dd on, 02e6
 * note, 02ef transpose (its instrument's), 02f8 the drum's note, 0301 the
 * drum's pitch, 030a the drum's program, 0313 the carrier's 0x40 byte
 * (KSL and level), 031c / 0325 the 0xA0 / 0xB0 bytes written, 032e age.
 * The instruments (01af, ten bytes each) are the modulator's 0x20, 0x40,
 * 0x60 and 0x80 bytes, the carrier's, 0xC0's and a transpose. 0012 is the
 * score's segment, 0014 the pitches (0xA0 | 0xB0 << 8, 96 notes of 12
 * F-numbers in blocks 0-7). Each port write is followed by a delay loop
 * (082e: 12 rounds after the address, 0810: 32 after the data), which
 * reads nothing back; their time is not modelled. */

static void opl(cok_sound *s, uint8_t reg, uint8_t value)
{
    out(s, 0x388, reg);
    out(s, 0x389, value);
}

/* 0836: the 102 registers at 00d6 (read from the last) to 0, then the 18
 * at 013c (0x80-0x95) to 0x3f. */
static void adlib_reset(cok_sound *s)
{
    for (int si = 0x65; si >= 0; --si) opl(s, MD[0xd6 + si], 0);
    for (int si = 0x11; si >= 0; --si) opl(s, MD[0x13c + si], 0x3f);
}

/* 0684: voice v to pitch bx (0xA0's byte, then 0xB0's with 034a, the
 * key-on bit, or'ed in), the carrier's level first with key-on: its 0x40
 * byte less a quarter of the velocity (a borrow reaching KSL's bits). */
static void adlib_note(cok_sound *s, unsigned v, uint16_t bx, uint8_t velocity)
{
    if (MD[0x34a] != 0)
        opl(s, (uint8_t)(MD[0x2cb + v] + 0x40), (uint8_t)(MD[0x313 + v] - (velocity >> 2)));
    MD[0x31c + v] = (uint8_t)bx;
    opl(s, (uint8_t)(0xa0 + v), (uint8_t)bx);
    uint8_t b0 = (uint8_t)(bx >> 8 | MD[0x34a]);
    MD[0x325 + v] = b0;
    opl(s, (uint8_t)(0xb0 + v), b0);
}

/* 06dc: voice v's F-number (from the bytes last written) times the bend
 * (034d, 0x2000 the middle) / 0x2000, the block and key-on kept; an
 * F-number past 0x3ff carries into the block's bits. Nothing divides, so
 * no bend ends the music on the AdLib. */
static void adlib_bend(cok_sound *s, unsigned v)
{
    uint8_t ah = MD[0x325 + v];
    MD[0x34f] = ah & 0xfc;
    uint32_t product = (uint32_t)((ah & 3u) << 8 | MD[0x31c + v]) * rw(MD, 0x34d);
    uint16_t bx = (uint16_t)(product >> 13);
    opl(s, (uint8_t)(0xa0 + v), (uint8_t)bx);
    opl(s, (uint8_t)(0xb0 + v), (uint8_t)(bx >> 8 | MD[0x34f]));
}

/* 0734: voice v takes program bl's instrument: the index at 0150, the
 * pointer at 0187 (both a byte's reach: a program past 0x36 reads beyond
 * them), its ten bytes to the voice's operators. */
static void adlib_instrument(cok_sound *s, unsigned v, uint8_t bl)
{
    uint8_t index = MD[(uint16_t)(0x150 + bl)];
    uint16_t di = rw(MD, (uint16_t)(0x187 + (uint8_t)(index << 1)));
    uint8_t mod = MD[0x2c2 + v], car = MD[0x2cb + v];
    opl(s, (uint8_t)(mod + 0x20), MD[di]);
    opl(s, (uint8_t)(mod + 0x40), MD[(uint16_t)(di + 1)]);
    opl(s, (uint8_t)(mod + 0x60), MD[(uint16_t)(di + 2)]);
    opl(s, (uint8_t)(mod + 0x80), MD[(uint16_t)(di + 3)]);
    opl(s, (uint8_t)(car + 0x20), MD[(uint16_t)(di + 4)]);
    MD[0x313 + v] = MD[(uint16_t)(di + 5)];
    opl(s, (uint8_t)(car + 0x40), MD[(uint16_t)(di + 5)]);
    opl(s, (uint8_t)(car + 0x60), MD[(uint16_t)(di + 6)]);
    opl(s, (uint8_t)(car + 0x80), MD[(uint16_t)(di + 7)]);
    opl(s, (uint8_t)(0xc0 + v), MD[(uint16_t)(di + 8)]);
    MD[0x2ef + v] = MD[(uint16_t)(di + 9)];
}

/* The pitch of note n (0014 + 2n, a byte's reach). */
static uint16_t adlib_pitch(cok_sound *s, uint8_t n)
{
    return rw(MD, (uint16_t)(0x14 + (uint8_t)(n << 1)));
}

/* 0376. */
static void adlib_play(cok_sound *s)
{
    ww(MD, 0x12, s->score_segment);
    uint16_t start = rw(SC, 0);
    ww(MD, 0x340, start);
    ww(MD, 0x342, start);
    for (unsigned di = 0; di < 9; ++di) MD[0x2d4 + di] = SC[0x22 + di];
    adlib_reset(s);
    for (unsigned di = 0; di < 9; ++di) {
        MD[0x2dd + di] = 0;
        MD[0x2e6 + di] = 0;
        ww(MD, (uint16_t)(0x32e + di * 2), 0);
    }
    /* The drums' voices (channel 9) take their programs now. */
    for (unsigned di = 0; di < 9; ++di)
        if (MD[0x2d4 + di] == 9) adlib_instrument(s, di, MD[0x30a + di]);
    MD[0x346] = 0;
    MD[0x350] = 0;
    MD[0x349] = 1;
}

/* 03e3. */
static void adlib_stop(cok_sound *s)
{
    MD[0x349] = 0;
    adlib_reset(s);
}

/* 0533: a note on (bl, velocity ah) on channel MD[0345]. */
static void adlib_note_on(cok_sound *s, uint8_t bl, uint8_t ah)
{
    uint8_t al = MD[0x345];
    if (al == 9) {
        /* 064d: the first of channel 9's voices whose drum it is. */
        for (unsigned di = 0; di < 9; ++di) {
            if (al != MD[0x2d4 + di] || bl != MD[0x2f8 + di]) continue;
            MD[0x34a] = 0x20;
            MD[0x2dd + di] = 1;
            MD[0x2e6 + di] = bl;
            adlib_note(s, di, adlib_pitch(s, MD[0x301 + di]), ah);
            return;
        }
        return;
    }
    for (unsigned di = 0; di < 9; ++di) {
        if (al != MD[0x2d4 + di] || MD[0x2dd + di] == 1) continue;
        MD[0x34a] = 0x20;
        MD[0x2dd + di] = 1;
        MD[0x2e6 + di] = bl;
        adlib_note(s, di, adlib_pitch(s, (uint8_t)(bl + MD[0x2ef + di])), ah);
        return;
    }
    /* 0580: every voice of the channel busy: the one sounding longest,
     * keyed off (pitch 0), takes the note; none older than 0, none. */
    uint16_t dx = 0;
    ww(MD, 0x34b, 0xffff);
    for (unsigned di = 0; di < 9; ++di) {
        if (al != MD[0x2d4 + di]) continue;
        uint16_t age = rw(MD, (uint16_t)(0x32e + di * 2));
        if (dx < age) {
            dx = age;
            ww(MD, 0x34b, di);
        }
    }
    if (rw(MD, 0x34b) == 0xffff) return;
    unsigned di = rw(MD, 0x34b);
    MD[0x34a] = 0;
    adlib_note(s, di, 0, ah);
    ww(MD, (uint16_t)(0x32e + di * 2), 0);
    MD[0x34a] = 0x20;
    MD[0x2dd + di] = 1;
    MD[0x2e6 + di] = bl;
    adlib_note(s, di, adlib_pitch(s, (uint8_t)(bl + MD[0x2ef + di])), ah);
}

/* 05f0: a note off, the channel's first voice on that note (on or not),
 * its pitch written again without key-on: a drum's at its pitch plus the
 * transpose its note on left out. */
static void adlib_note_off(cok_sound *s, uint8_t bl)
{
    uint8_t al = MD[0x345];
    for (unsigned di = 0; di < 9; ++di) {
        if (al != MD[0x2d4 + di] || MD[0x2e6 + di] != bl) continue;
        MD[0x34a] = 0;
        MD[0x2dd + di] = 0;
        uint8_t note = al == 9 ? MD[0x301 + di] : MD[0x2e6 + di];
        MD[0x2e6 + di] = 0;
        uint16_t bx = adlib_pitch(s, (uint8_t)(note + MD[0x2ef + di]));
        ww(MD, (uint16_t)(0x32e + di * 2), 0);
        adlib_note(s, di, bx, 0);
        return;
    }
}

/* 03ee: a tick: the ages of the voices on, then the score's events due. */
static void adlib_tick(cok_sound *s)
{
    if (MD[0x349] != 1) return;
    uint16_t si = rw(MD, 0x340);
    uint8_t al, ah = 0;
    for (unsigned di = 0; di < 9; ++di) {
        uint16_t age = (uint16_t)(0x32e + di * 2);
        if (MD[0x2dd + di] == 1) ww(MD, age, rw(MD, age) + 1u);
    }
    if (MD[0x346] != 0) {
        --MD[0x346];
        goto done;
    }
    for (int steps = 0; steps < STEPS_MAX; ++steps) {
        al = SC[si++];
        if (al < 0x80) {
            /* Running status. */
            ah = MD[0x344];
            --si;
            if (MD[0x347] != 0) {
                ++si;
                if (MD[0x348] != 0) ++si;
                goto delta;
            }
        } else if (al == 0xfc) {
            al = SC[si++];
            if (al == 0x80) {
                si = rw(MD, 0x342);
                continue;
            }
            /* The end: the voices sounding go on (until AH 2). */
            MD[0x349] = 0;
            return;
        } else {
            MD[0x345] = al & 0x0f;
            ah = al & 0xf0;
            MD[0x344] = ah;
        }
        if (ah == 0xe0) {
            MD[0x348] = 1;
            uint8_t dl = SC[si++];
            uint8_t dh = SC[si++];
            if (dh & 1) dl |= 0x80;
            dh >>= 1;
            ww(MD, 0x34d, (unsigned)dh << 8 | dl);
            for (unsigned di = 0; di < 9; ++di)
                if (MD[0x345] == MD[0x2d4 + di] && MD[0x2dd + di] == 1) adlib_bend(s, di);
            goto delta;
        }
        MD[0x347] = 0;
        MD[0x348] = 1;
        if (ah == 0xc0) {
            /* 04eb: the channel's voices (not channel 9's) take the program. */
            MD[0x348] = 0;
            uint8_t bl = SC[si++];
            for (unsigned di = 0; di < 9; ++di)
                if (MD[0x345] != 9 && MD[0x345] == MD[0x2d4 + di]) adlib_instrument(s, di, bl);
            goto delta;
        }
        if (ah == 0x90 && SC[(uint16_t)(si + 1)] != 0) {
            uint8_t bl = SC[si], velocity = SC[(uint16_t)(si + 1)];
            si = (uint16_t)(si + 2);
            adlib_note_on(s, bl, velocity);
            goto delta;
        }
        if (ah == 0x90 || ah == 0x80) {
            uint8_t bl = SC[si];
            si = (uint16_t)(si + 2);
            adlib_note_off(s, bl);
            goto delta;
        }
        /* Any other status: two bytes skipped, and after it too. */
        si = (uint16_t)(si + 2);
        MD[0x348] = 1;
        MD[0x347] = 1;
    delta:
        al = SC[si++];
        if (al == 0) continue;
        MD[0x346] = (uint8_t)(al - 1);
        break;
    }
done:
    ww(MD, 0x340, si);
}

/* Tandy (record 4). Voices 0-3 (3 the noise): per voice at 018a channel,
 * 018e transpose, 0192 on, 0196 note, 019a envelope speed, 019e its count,
 * 01a2 envelope running, 01a6 first level, 01aa level, 01ae bent this
 * tick, 01b2/01ba envelope start/place, 01c2 vibrato divisor, 01c6/01ce
 * vibrato place/start, 01d6 pitch, 01de/01e2 latches, 01e6 age. */

/* 0570: the pitch bx to the voice (two bytes; the noise voice's latch is
 * 0, so both go to the register latched last). */
static void tandy_pitch(cok_sound *s, unsigned di, uint16_t bx)
{
    out(s, 0xc0, (uint8_t)((bx & 0x0f) | MD[0x1de + di]));
    out(s, 0xc0, (uint8_t)((bx >> 4) & 0x3f));
}

/* 058e: the voice takes program bl's instrument. */
static void tandy_instrument(cok_sound *s, unsigned di, uint8_t bl)
{
    uint8_t index = MD[(uint16_t)(0x7e + bl)];
    uint16_t record = rw(MD, (uint16_t)(0x88 + (uint8_t)(index << 1)));
    uint16_t envelope = rw(MD, record);
    MD[0x19a + di] = MD[(uint16_t)(envelope - 1)];
    MD[0x1a6 + di] = MD[envelope];
    ww(MD, (uint16_t)(0x1b2 + di * 2), envelope);
    ww(MD, (uint16_t)(0x1ce + di * 2), rw(MD, (uint16_t)(record + 2)));
    MD[0x1c2 + di] = MD[(uint16_t)(record + 4)];
}

static void music_divide_error(cok_sound *s)
{
    /* Turbo Pascal's runtime error 200 in the original. */
    s->divide_error = true;
    MD[0x1f7] = 0;
}

/* 05c4: pitch * 0x2000 / the bend. Returns the pitch written. */
static bool tandy_bend(cok_sound *s, unsigned di, uint16_t *bx)
{
    uint32_t product = (uint32_t)rw(MD, (uint16_t)(0x1d6 + di * 2)) * 0x2000u;
    uint16_t bend = rw(MD, 0x1fb);
    if (bend == 0 || product / bend > 0xffff) {
        music_divide_error(s);
        return false;
    }
    *bx = (uint16_t)(product / bend);
    tandy_pitch(s, di, *bx);
    return true;
}

/* 05df: a voice's tick: its envelope, then its vibrato unless bent. */
static bool tandy_voice(cok_sound *s, unsigned di)
{
    uint16_t bx = (uint16_t)(di * 2);
    if (MD[0x1a2 + di] != 0 && --MD[0x19e + di] == 0) {
        MD[0x19e + di] = MD[0x19a + di];
        uint16_t at = rw(MD, (uint16_t)(0x1ba + bx));
        uint8_t level = MD[at];
        if (level != 0xff) {
            ww(MD, (uint16_t)(0x1ba + bx), at + 1u);
            MD[0x1aa + di] = level;
            out(s, 0xc0, (uint8_t)(level | MD[0x1e2 + di]));
        }
    }
    uint8_t dl = MD[0x1c2 + di];
    if (dl == 0 || MD[0x1ae + di] == 1) return true;
    uint16_t pitch = rw(MD, (uint16_t)(0x1d6 + bx));
    if (pitch / dl > 0xff) {
        music_divide_error(s);
        return false;
    }
    uint8_t quotient = (uint8_t)(pitch / dl);
    uint16_t at = rw(MD, (uint16_t)(0x1c6 + bx));
    dl = MD[at];
    if (dl == 0x80) {
        at = rw(MD, (uint16_t)(0x1ce + bx));
        dl = MD[at];
    }
    uint16_t ax = (uint16_t)(s8(quotient) * s8(dl) + pitch);
    ww(MD, (uint16_t)(0x1c6 + bx), at + 1u);
    tandy_pitch(s, di, ax >= 0x3ff ? 0x3ff : ax);
    return true;
}

static void tandy_play(cok_sound *s)
{
    ww(MD, 0x12, s->score_segment);
    uint16_t start = rw(SC, 0);
    ww(MD, 0x1ee, start);
    ww(MD, 0x1f0, start);
    for (unsigned di = 0; di < 8; ++di) MD[0x18a + di] = SC[0x43 + di];
    for (unsigned di = 0; di < 4; ++di) {
        MD[0x192 + di] = 0;
        MD[0x196 + di] = 0;
        ww(MD, (uint16_t)(0x1e6 + di * 2), 0);
        MD[0x1aa + di] = 0x0f;
        MD[0x1c2 + di] = 0;
        MD[0x1ae + di] = 0;
        MD[0x1a2 + di] = 0;
    }
    silence_tandy(s);
    MD[0x1f4] = 0;
    MD[0x1f8] = 0;
    MD[0x1f7] = 1;
}

static void tandy_stop(cok_sound *s)
{
    MD[0x1f7] = 0;
    silence_tandy(s);
}

/* 02aa: a tick: the score's events due, then every voice's tick. bx is
 * the register as the events leave it, which a drum's voice takes as its
 * pitch's high byte (045f). */
static void tandy_tick(cok_sound *s)
{
    if (MD[0x1f7] != 1) return;
    uint16_t si = rw(MD, 0x1ee), bx = 0;
    uint8_t al, ah = 0;
    unsigned di = 0;
    if (MD[0x1f4] != 0) {
        --MD[0x1f4];
        goto voices;
    }
    for (int steps = 0; steps < STEPS_MAX; ++steps) {
        al = SC[si++];
        if (al < 0x80) {
            /* Running status. */
            ah = MD[0x1f2];
            --si;
            if (MD[0x1f5] != 0) {
                ++si;
                if (MD[0x1f6] != 0) ++si;
                goto delta;
            }
        } else if (al == 0xfc) {
            al = SC[si++];
            if (al == 0x80) {
                si = rw(MD, 0x1f0);
                continue;
            }
            MD[0x1f7] = 0;
            silence_tandy(s);
            return;
        } else {
            MD[0x1f3] = al & 0x0f;
            ah = al & 0xf0;
            MD[0x1f2] = ah;
        }
        if (ah == 0xe0) {
            MD[0x1f6] = 1;
            uint8_t dl = SC[si++];
            uint8_t dh = SC[si++];
            if (dh & 1) dl |= 0x80;
            dh >>= 1;
            ww(MD, 0x1fb, (unsigned)dh << 8 | dl);
            al = MD[0x1f3];
            for (di = 0; di < 3; ++di) {
                if (al != MD[0x18a + di] || MD[0x192 + di] != 1) continue;
                MD[0x1ae + di] = 1;
                if (!tandy_bend(s, di, &bx)) return;
            }
            goto delta;
        }
        MD[0x1f5] = 0;
        MD[0x1f6] = 1;
        if (ah == 0xc0) {
            MD[0x1f6] = 0;
            bx = (uint16_t)((bx & 0xff00) | SC[si++]);
            for (di = 0; di < 4; ++di) {
                al = MD[0x1f3];
                if (al != 9 && al == MD[0x18a + di]) tandy_instrument(s, di, (uint8_t)bx);
            }
            goto delta;
        }
        if (ah == 0x90 && SC[(uint16_t)(si + 1)] != 0) {
            uint8_t note = SC[si];
            si = (uint16_t)(si + 2);
            bx = (uint16_t)((bx & 0xff00) | note);
            al = MD[0x1f3];
            if (al == 9) {
                /* 0529: the drums, on the noise voice. */
                uint8_t instrument, control;
                if (note == 0x24) {
                    instrument = 0x11;
                    control = 0xe6;
                } else if (note == 0x26) {
                    instrument = 0x10;
                    control = 0xe4;
                } else {
                    goto delta;
                }
                di = 3;
                bx = (uint16_t)((bx & 0xff00) | instrument);
                tandy_instrument(s, 3, instrument);
                out(s, 0xc0, control);
                goto start;
            }
            for (di = 0; di < 4; ++di)
                if (al == MD[0x18a + di] && MD[0x192 + di] != 1) break;
            if (di == 4) {
                /* 049a: steal the channel's voice sounding longest. */
                uint16_t oldest = 0;
                ww(MD, 0x1f9, 0xffff);
                for (di = 0; di < 4; ++di) {
                    if (al != MD[0x18a + di]) continue;
                    uint16_t age = rw(MD, (uint16_t)(0x1e6 + di * 2));
                    if (oldest < age) {
                        oldest = age;
                        ww(MD, 0x1f9, di);
                    }
                }
                if (rw(MD, 0x1f9) == 0xffff) goto delta;
                di = rw(MD, 0x1f9);
                ww(MD, (uint16_t)(0x1e6 + di * 2), 0);
            }
            /* 0429. */
            MD[0x192 + di] = 1;
            MD[0x196 + di] = note;
            uint8_t bl = (uint8_t)(note + MD[0x18e + di]);
            if (s8(bl) < 0) {
                do bl = (uint8_t)(bl + 12);
                while (s8(bl) < 0);
            } else {
                while (s8(bl) > 0x32) bl = (uint8_t)(bl - 12);
            }
            bx = rw(MD, (uint16_t)(0x18 + (uint8_t)(bl << 1)));
            tandy_pitch(s, di, bx);
        start:
            /* 045f: the envelope from its start, the vibrato too. */
            MD[0x19e + di] = MD[0x19a + di];
            al = MD[0x1a6 + di];
            MD[0x1aa + di] = al;
            MD[0x1a2 + di] = 1;
            out(s, 0xc0, (uint8_t)(al | MD[0x1e2 + di]));
            ww(MD, (uint16_t)(0x1ba + di * 2), rw(MD, (uint16_t)(0x1b2 + di * 2)));
            ww(MD, (uint16_t)(0x1d6 + di * 2), bx);
            ww(MD, (uint16_t)(0x1c6 + di * 2), rw(MD, (uint16_t)(0x1ce + di * 2)));
            goto delta;
        }
        if (ah == 0x90 || ah == 0x80) {
            /* 04e2: note off, the channel's first voice on that note. */
            uint8_t note = SC[si];
            si = (uint16_t)(si + 2);
            bx = (uint16_t)((bx & 0xff00) | note);
            al = MD[0x1f3];
            for (di = 0; di < 4; ++di) {
                if (al != MD[0x18a + di] || MD[0x196 + di] != note) continue;
                MD[0x192 + di] = 0;
                MD[0x196 + di] = 0;
                MD[0x1aa + di] = 0x0f;
                out(s, 0xc0, (uint8_t)(0x0f | MD[0x1e2 + di]));
                MD[0x1a2 + di] = 0;
                ww(MD, (uint16_t)(0x1e6 + di * 2), 0);
                break;
            }
            goto delta;
        }
        /* Any other status: two bytes skipped, and after it too. */
        si = (uint16_t)(si + 2);
        MD[0x1f6] = 1;
        MD[0x1f5] = 1;
    delta:
        al = SC[si++];
        if (al == 0) continue;
        MD[0x1f4] = (uint8_t)(al - 1);
        break;
    }
voices:
    ww(MD, 0x1ee, si);
    for (di = 0; di < 4; ++di) {
        if (!tandy_voice(s, di)) return;
        MD[0x1ae + di] = 0;
        uint16_t age = (uint16_t)(0x1e6 + di * 2);
        if (MD[0x192 + di] == 1) ww(MD, age, rw(MD, age) + 1u);
    }
}

/* The speaker (record 5): one voice, the channel at score byte 0x4b
 * (00d8) transposed by 0x4c (00d9); the drums (channel 15, notes 0 and 1)
 * run little pitch scripts (0108, 0111) each tick (031e). */

static void speaker_pitch(cok_sound *s, uint16_t pitch)
{
    out(s, 0x42, (uint8_t)pitch);
    out(s, 0x42, (uint8_t)(pitch >> 8));
}

static void speaker_on(cok_sound *s)
{
    out(s, 0x61, (uint8_t)(s->port61 | 3));
}

static void speaker_off(cok_sound *s)
{
    out(s, 0x61, (uint8_t)(s->port61 & 0xfc));
}

/* 040f: a pseudo-random word at 0104. */
static uint16_t speaker_random(cok_sound *s)
{
    uint8_t seed = MD[0x104];
    uint8_t cf = (uint8_t)(((seed >> 1) & 1) ^ 1); /* SHR twice, CMC */
    uint8_t al = (uint8_t)((seed >> 2) - seed - cf);  /* SBB */
    cf = al & 1;                                      /* SHR */
    uint8_t high = MD[0x105];
    MD[0x105] = (uint8_t)(high << 1 | cf);            /* RCL */
    cf = (uint8_t)(high >> 7);
    MD[0x104] = (uint8_t)(cf << 7 | MD[0x104] >> 1);  /* RCR */
    return rw(MD, 0x104);
}

/* 03e8: start a drum's script at ax. */
static void speaker_drum(cok_sound *s, uint16_t ax)
{
    ww(MD, 0xfa, ax);
    ww(MD, 0xfc, ax);
    MD[0xef] = 0;
    MD[0xf1] = 0;
    speaker_on(s);
    out(s, 0x43, 0xb6);
    out(s, 0x42, 0x01);
    out(s, 0x42, 0x00);
    MD[0xed] = 1;
}

/* 031e: the drum's tick. */
static void speaker_effect(cok_sound *s)
{
    if (MD[0xed] != 1) return;
    if (MD[0xef] != 0) {
        if (MD[0xee] != 0) {
            uint16_t ax = (uint16_t)(speaker_random(s) & rw(MD, 0xfe));
            --MD[0xef];
            speaker_pitch(s, ax);
            return;
        }
        ww(MD, 0xf6, rw(MD, 0xf6) + rw(MD, 0xf8));
        --MD[0xef];
        speaker_pitch(s, rw(MD, 0xf6));
        return;
    }
    if (MD[0xf1] != 0) {
        --MD[0xf1];
        ww(MD, 0xf6, rw(MD, 0xf4));
        MD[0xef] = MD[0xf0];
        speaker_pitch(s, rw(MD, 0xf6));
        return;
    }
    uint16_t at = rw(MD, 0xfc);
    MD[0xee] = 0;
    for (int steps = 0; steps < STEPS_MAX; ++steps) {
        uint8_t op = MD[at];
        at = (uint16_t)(at + 1);
        switch (op) {
        case 0x84:
            speaker_off(s);
            MD[0xed] = 0;
            return;
        case 0x83:
            MD[0xef] = MD[0xf0] = MD[at];
            ww(MD, 0xf4, rw(MD, (uint16_t)(at + 1)));
            ww(MD, 0xf6, rw(MD, (uint16_t)(at + 1)));
            ww(MD, 0xf8, rw(MD, (uint16_t)(at + 3)));
            ww(MD, 0xfc, (uint16_t)(at + 5));
            speaker_pitch(s, rw(MD, 0xf6));
            return;
        case 0x81:
            MD[0xf1] = MD[at];
            at = (uint16_t)(at + 1);
            break;
        case 0x87:
            at = rw(MD, 0xfa);
            break;
        case 0x82:
            MD[0xee] = 1;
            MD[0xef] = MD[0xf0] = MD[at];
            ww(MD, 0xfe, rw(MD, (uint16_t)(at + 1)));
            ww(MD, 0xfc, (uint16_t)(at + 3));
            speaker_pitch(s, rw(MD, 0xf6));
            return;
        default:
            break;
        }
    }
}

static void speaker_play(cok_sound *s)
{
    ww(MD, 0x12, s->score_segment);
    uint16_t start = rw(SC, 0);
    ww(MD, 0xe0, start);
    ww(MD, 0xe2, start);
    MD[0xd8] = SC[0x4b];
    MD[0xd9] = SC[0x4c];
    MD[0xda] = 0;
    MD[0xdb] = 0;
    ww(MD, 0xde, 0);
    MD[0xe6] = 0;
    speaker_on(s);
    speaker_off(s);
    out(s, 0x43, 0xb6);
    out(s, 0x42, 0x01);
    out(s, 0x42, 0x00);
    MD[0xea] = 0;
    MD[0xe9] = 1;
    MD[0xed] = 0;
}

static void speaker_stop(cok_sound *s)
{
    MD[0xe9] = 0;
    speaker_off(s);
    MD[0xed] = 0;
}

/* 01b0. */
static void speaker_tick(cok_sound *s)
{
    if (MD[0xe9] != 1) return;
    uint16_t si = rw(MD, 0xe0);
    uint8_t al, ah = 0;
    if (MD[0xe6] != 0) {
        --MD[0xe6];
        goto tail;
    }
    for (int steps = 0; steps < STEPS_MAX; ++steps) {
        al = SC[si++];
        if (al < 0x80) {
            ah = MD[0xe4];
            --si;
            if (MD[0xe7] != 0) {
                ++si;
                if (MD[0xe8] != 0) ++si;
                goto delta;
            }
        } else if (al == 0xfc) {
            al = SC[si++];
            if (al == 0x80) {
                si = rw(MD, 0xe2);
                continue;
            }
            MD[0xe9] = 0;
            MD[0xed] = 0;
            speaker_off(s);
            return;
        } else {
            MD[0xe5] = al & 0x0f;
            ah = al & 0xf0;
            MD[0xe4] = ah;
        }
        if (ah == 0xe0) {
            MD[0xe8] = 1;
            MD[0xe7] = 1;
            si = (uint16_t)(si + 2);
            goto delta;
        }
        MD[0xe7] = 0;
        MD[0xe8] = 1;
        if (ah == 0xc0) {
            MD[0xe8] = 0;
            ++si;
            goto delta;
        }
        if (ah == 0x90 && SC[(uint16_t)(si + 1)] != 0) {
            uint8_t note = SC[si];
            si = (uint16_t)(si + 2);
            al = MD[0xe5];
            if (al == 0x0f) {
                if (note == 0)
                    speaker_drum(s, 0x108);
                else if (note == 1)
                    speaker_drum(s, 0x111);
            } else if (al == MD[0xd8]) {
                MD[0xda] = 1;
                MD[0xdb] = note;
                uint8_t bl = (uint8_t)(note + MD[0xd9]);
                uint16_t pitch = rw(MD, (uint16_t)(0x18 + (uint8_t)(bl << 1)));
                ww(MD, 0xdc, pitch);
                speaker_on(s);
                speaker_pitch(s, pitch);
            }
            goto delta;
        }
        if (ah == 0x90 || ah == 0x80) {
            si = (uint16_t)(si + 2);
            if (MD[0xe5] == MD[0xd8]) {
                MD[0xda] = 0;
                speaker_off(s);
            }
            goto delta;
        }
        si = (uint16_t)(si + 2);
        MD[0xe8] = 1;
        MD[0xe7] = 1;
    delta:
        al = SC[si++];
        if (al == 0) continue;
        MD[0xe6] = (uint8_t)(al - 1);
        break;
    }
tail:
    ww(MD, 0xe0, si);
    speaker_effect(s);
}

/* The driver's entry (0203 / 0120): AH's routine from its table. */
static void music_call(cok_sound *s, unsigned ah)
{
    const music_entry *e = music_driver(s);
    uint16_t routine = rw(MD, (uint16_t)(e->table + 2 * ah));
    if (s->hardware == COK_SOUND_TANDY) {
        if (routine == e->tick) tandy_tick(s);
        else if (routine == e->play) tandy_play(s);
        else if (routine == e->stop) tandy_stop(s);
    } else if (s->hardware == COK_SOUND_ADLIB) {
        if (routine == e->tick) adlib_tick(s);
        else if (routine == e->play) adlib_play(s);
        else if (routine == e->stop) adlib_stop(s);
    } else {
        if (routine == e->tick) speaker_tick(s);
        else if (routine == e->play) speaker_play(s);
        else if (routine == e->stop) speaker_stop(s);
    }
}

/* 2f55:063c's part: 1661:000a (the driver loaded afresh), 02e6 (INT 8
 * hooked, PIT channel 0 at 0x5555), 014d (the score), 02b3 (play). */
static void title_start(cok_sound *s)
{
    s->music = true;
    if (s->device == COK_SOUND_NONE || s->driver == NULL || s->score == NULL) return;
    memset(MD, 0, sizeof MD);
    memcpy(MD, s->driver, s->driver_size);
    memset(SC, 0, sizeof SC);
    memcpy(SC, s->score, s->score_size);
    s->title_saved = s->isr;
    s->isr = COK_SOUND_TITLE;
    s->title_count = 3;
    out(s, 0x43, 0x36);
    out(s, 0x40, 0x55);
    out(s, 0x40, 0x55);
    s->music_loaded = true;
    music_call(s, 1);
}

/* 1661:0353 (stop) and 00da (INT 8 back, PIT 0xffff). */
static void title_stop(cok_sound *s)
{
    if (!s->music_loaded) return;
    music_call(s, 2);
    s->isr = s->title_saved;
    out(s, 0x40, 0xff);
    out(s, 0x40, 0xff);
    s->music_loaded = false;
}

/* 1661:035a. */
static void title_interrupt(cok_sound *s)
{
    if (!s->title_busy) {
        s->title_busy = true;
        music_call(s, 0);
        s->title_busy = false;
    }
    if (--s->title_count == 0) {
        s->title_count = 3;
        chain(s, s->title_saved);
    }
}

/* A handler's jump to the one it replaced: the BIOS's tick does nothing
 * here; a driver hooked twice runs again (never in the game). */
static void chain(cok_sound *s, cok_sound_isr to)
{
    if (to == COK_SOUND_FX)
        fx_interrupt(s);
    else if (to == COK_SOUND_TITLE)
        title_interrupt(s);
}

/* The game's calls. */

void cok_sound_call_at(cok_sound *s, cok_sound_call call, unsigned value)
{
    switch (call) {
    case COK_SOUND_COMMAND:
        cok_sound_command(s, value);
        break;
    case COK_SOUND_INSTALL:
        fx_install(s);
        break;
    case COK_SOUND_OVERLAY:
        if (s->installed) cok_sound_command(s, 0xff);
        break;
    case COK_SOUND_OVERLAY_END:
        if (!s->installed) fx_install(s);
        break;
    case COK_SOUND_RECORD:
        cok_sound_command(s, 0);
        cok_sound_command(s, 1);
        break;
    case COK_SOUND_CTRL_S:
        /* 1614:025b: Ctrl-S, but not while the title's music plays. */
        if (s->music) break;
        if (s->device != COK_SOUND_NONE) {
            s->saved = s->device;
            cok_sound_command(s, 0);
            s->device = COK_SOUND_NONE;
        } else if (s->saved < 8 && (CTRL_S_DEVICES & (1u << s->saved)) != 0) {
            s->device = s->saved;
            cok_sound_command(s, 1);
        }
        break;
    case COK_SOUND_MUSIC:
        title_start(s);
        break;
    case COK_SOUND_MUSIC_END:
        /* 2f55:006d. */
        if (s->device != COK_SOUND_NONE) title_stop(s);
        s->music = false;
        break;
    case COK_SOUND_QUIT:
        /* 1614:0000. */
        s->device = s->saved;
        if (!s->music)
            cok_sound_command(s, 0xff);
        else if (s->device != COK_SOUND_NONE)
            title_stop(s);
        break;
    }
}

/* Time. */

static uint64_t tick_clocks(const cok_sound *s)
{
    return (uint64_t)(s->pit0 != 0 ? s->pit0 : 65536) * PIT_CLOCKS;
}

static void interrupt(cok_sound *s)
{
    if (s->bomb) return;
    if (s->isr == COK_SOUND_FX)
        fx_interrupt(s);
    else if (s->isr == COK_SOUND_TITLE)
        title_interrupt(s);
}

void cok_sound_tick(cok_sound *s)
{
    if (s->next_tick > s->now) s->now = s->next_tick;
    s->next_tick += tick_clocks(s);
    interrupt(s);
}

static void pit2_clock(cok_sound *s)
{
    if ((s->port61 & 1) == 0 || s->pit2_waiting) return;
    if (s->pit2_left > 1) {
        --s->pit2_left;
        return;
    }
    s->pit2_out = !s->pit2_out;
    s->pit2_left = pit2_half(s, s->pit2_out);
}

void cok_sound_render(cok_sound *s, int16_t *samples, size_t frames)
{
    for (size_t i = 0; i < frames; ++i) {
        uint64_t end = s->now + SAMPLE_CLOCKS;
        s->frac += SAMPLE_FRAC;
        if (s->frac >= SAMPLE_DEN) {
            s->frac -= SAMPLE_DEN;
            ++end;
        }
        while (s->next_tick < end) cok_sound_tick(s);
        s->now = end;
        int64_t level = 0, sum = 0, n = 0;
        while (s->chip_next < end) {
            cok_sound_chip_step(&s->chip);
            sum += cok_sound_chip_level(&s->chip);
            ++n;
            s->chip_next += CHIP_CLOCKS;
        }
        if (n > 0 && s->hardware == COK_SOUND_TANDY) level += sum / n;
        sum = n = 0;
        while (s->pit2_next < end) {
            pit2_clock(s);
            sum += s->pit2_out && (s->port61 & 2) != 0 ? SPEAKER_LEVEL : 0;
            ++n;
            s->pit2_next += PIT_CLOCKS;
        }
        if (n > 0) level += sum / n;
        if (s->hardware == COK_SOUND_ADLIB) {
            sum = n = 0;
            while (s->opl_next < end) {
                sum += cok_opl2_sample(&s->opl);
                ++n;
                s->opl_next += OPL_CLOCKS;
            }
            if (n > 0) level += sum * OPL_GAIN / n;
        }
        /* The output's coupling capacitor: a high-pass at about 14 Hz. */
        int64_t y = level - s->dc_in + s->dc_out * 65404 / 65536;
        s->dc_in = level;
        s->dc_out = y;
        int64_t v = y * (int64_t)s->volume / 256;
        samples[i] = (int16_t)(v > 32767 ? 32767 : v < -32768 ? -32768 : v);
    }
}

/* Setup. */

void cok_sound_init(cok_sound *s, cok_sound_device hardware)
{
    memset(s, 0, sizeof *s);
    /* The Tandy's chip for the Tandy (and none); a PC's speaker for the
     * others, whose effects play there, and the AdLib's chip beside it. */
    s->hardware = hardware == COK_SOUND_TANDY || hardware == COK_SOUND_NONE ? COK_SOUND_TANDY
                  : hardware == COK_SOUND_ADLIB                              ? COK_SOUND_ADLIB
                                                                             : COK_SOUND_SPEAKER;
    s->device = (uint8_t)hardware; /* DS:577b is 0 until 00da copies it. */
    memcpy(s->fx, fx_image, sizeof fx_image);
    ww(s->fx, 0x124, 0); /* 17e8:0105 */
    s->isr = s->fx_saved = s->title_saved = COK_SOUND_BIOS;
    s->pit0 = 0;
    s->next_tick = 65536ull * PIT_CLOCKS;
    s->pit2_out = true;
    s->pit2_left = 1;
    cok_sound_chip_init(&s->chip);
    cok_opl2_init(&s->opl);
    s->volume = 256;
}

static uint8_t *load_record(const char *assets, const char *name, uint8_t id, size_t *size,
                            char *error, size_t error_size)
{
    char path[1024];
    snprintf(path, sizeof path, "%.1000s/%s.DAX", assets, name);
    dax_archive archive = {0};
    dax_status status = dax_open(path, &archive);
    if (status != DAX_OK) {
        snprintf(error, error_size, "%s: %s", path, dax_status_string(status));
        return NULL;
    }
    uint8_t *data = NULL;
    for (size_t i = 0; i < archive.count && data == NULL; ++i) {
        dax_record record;
        if (dax_record_at(&archive, i, &record) != DAX_OK || record.id != id) continue;
        data = malloc(record.decoded_size == 0 ? 1 : record.decoded_size);
        if (data == NULL) break;
        status = dax_decode(record.packed, record.packed_size, data, record.decoded_size);
        if (status != DAX_OK) {
            free(data);
            data = NULL;
            break;
        }
        *size = record.decoded_size;
    }
    if (data == NULL)
        snprintf(error, error_size, "%s: no record %u (%s)", path, id, dax_status_string(status));
    dax_close(&archive);
    return data;
}

bool cok_sound_load(cok_sound *s, const cok_rules *rules, const char *assets)
{
    cok_sound_free(s);
    s->music_error[0] = '\0';
    const char *drivers = rules->archives.music_drivers;
    if (drivers == NULL || rules->archives.music_score == NULL) {
        /* A game whose music the port does not read yet (Death Knights'
         * MUSIC.DAX, DEATH-KNIGHTS.md's step 4). */
        snprintf(s->music_error, sizeof s->music_error, "%s's music is not ported",
                 rules->text.name);
        return false;
    }
    if (s->device < COK_SOUND_ADLIB) {
        snprintf(s->music_error, sizeof s->music_error,
                 "the music driver for %s (%s.DAX record %u) is not ported",
                 cok_sound_device_name((cok_sound_device)s->device), drivers, s->device + 1u);
        return false;
    }
    uint8_t id = s->hardware == COK_SOUND_TANDY ? 4 : s->hardware == COK_SOUND_ADLIB ? 3 : 5;
    size_t driver_size = 0, score_size = 0;
    uint8_t *driver = load_record(assets, drivers, id, &driver_size, s->music_error,
                                  sizeof s->music_error);
    if (driver == NULL) return false;
    const music_entry *e = music_driver(s);
    if (driver_size < 0x200 || rw(driver, e->table) != e->tick ||
        rw(driver, (uint16_t)(e->table + 2)) != e->play ||
        rw(driver, (uint16_t)(e->table + 4)) != e->stop) {
        snprintf(s->music_error, sizeof s->music_error,
                 "%s/%s.DAX record %u is not the driver this port knows", assets, drivers, id);
        free(driver);
        return false;
    }
    uint8_t *score = load_record(assets, rules->archives.music_score, 1, &score_size,
                                 s->music_error, sizeof s->music_error);
    if (score == NULL) {
        free(driver);
        return false;
    }
    s->driver = driver;
    s->driver_size = driver_size;
    s->score = score;
    s->score_size = score_size;
    return true;
}

void cok_sound_free(cok_sound *s)
{
    free(s->driver);
    free(s->score);
    s->driver = s->score = NULL;
    s->driver_size = s->score_size = 0;
}

/* The devices KRYNN.CFG names (config.h). */

const char *cok_sound_device_name(cok_sound_device device)
{
    static const char *const names[] = {"C/MS", "Roland LAPC", "AdLib", "Tandy 1000", "PC",
                                        "Silent"};
    return device <= COK_SOUND_NONE ? names[device] : "Silent";
}

bool cok_sound_music_unported(const cok_sound *s, const cok_rules *rules, char *text,
                              size_t size)
{
    if (!s->music || s->device >= COK_SOUND_TANDY) return false;
    /* The AdLib's is ported, but not a game's whose music is not read. */
    if (s->device == COK_SOUND_ADLIB && rules->archives.music_drivers != NULL) return false;
    snprintf(text, size, "the title's music on %s (%s.DAX record %u)",
             cok_sound_device_name((cok_sound_device)s->device),
             rules->archives.music_drivers, s->device + 1u);
    return true;
}
