/* 1614:022c: the devices Ctrl-S turns back on, a Pascal set: {3, 4}. */
enum { CTRL_S_DEVICES = 0x18 };

/* Time is counted in clocks of the 14,318,181.8 Hz crystal (157,500,000 / 11
 * Hz): the PIT counts every 12th, the Tandy's chip steps every 64th
 * (3,579,545 Hz / 16), the AdLib's makes a sample every 288th (its own
 * 3,579,545 Hz crystal, a quarter of the PC's, / 72: 49,716 Hz). A sample
 * at 44,100 Hz is 324 + 327,600 / 485,100 of them. */
enum {
    PIT_CLOCKS = 12,
    CHIP_CLOCKS = 64,
    OPL_CLOCKS = 4 * COK_OPL2_CLOCKS,
    SAMPLE_CLOCKS = 324,
    SAMPLE_FRAC = 327600,
    SAMPLE_DEN = 485100,
    SPEAKER_LEVEL = 8191,
    OPL_GAIN = 1,        /* the AdLib's sum to the mix: see DEVELOPERS.md, The hardware */
    STEPS_MAX = 100000, /* A script or envelope looping forever (the original hangs). */
};

static inline uint16_t rw(const uint8_t *seg, uint16_t at)
{
    return (uint16_t)(seg[at] | seg[(uint16_t)(at + 1)] << 8);
}

static inline void ww(uint8_t *seg, uint16_t at, unsigned value)
{
    seg[at] = (uint8_t)value;
    seg[(uint16_t)(at + 1)] = (uint8_t)(value >> 8);
}

static inline int32_t s16(uint16_t v)
{
    return v >= 0x8000 ? (int32_t)v - 0x10000 : (int32_t)v;
}

static inline int32_t s8(uint8_t v)
{
    return v >= 0x80 ? (int32_t)v - 0x100 : (int32_t)v;
}

/* SAR: an arithmetic shift right of a word. */
static inline uint16_t sar(uint16_t v, unsigned n)
{
    return (uint16_t)(s16(v) >= 0 ? v >> n : ~((uint16_t)~v >> n));
}

